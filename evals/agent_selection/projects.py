def git(root, *args):
    env = dict(os.environ, GIT_AUTHOR_NAME="Dev", GIT_AUTHOR_EMAIL="dev@example.com",
               GIT_COMMITTER_NAME="Dev", GIT_COMMITTER_EMAIL="dev@example.com",
               GIT_AUTHOR_DATE="2026-09-01T10:00:00", GIT_COMMITTER_DATE="2026-09-01T10:00:00")
    subprocess.run(["git", "-C", str(root), "-c", "init.defaultBranch=main", *args],
                   check=True, capture_output=True, env=env)


def write_files(root, files):
    for rel, content in files.items():
        path = os.path.join(root, rel)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        mode = "wb" if isinstance(content, bytes) else "w"
        with open(path, mode) as f:
            f.write(content)


def build(name, root, setup=None):
    """Create project NAME at ROOT as a git repository with one commit, then apply SETUP:
    {"commit": {path: content or None}, "edit": {path: content or None}} (None deletes)."""
    os.makedirs(root)
    write_files(root, PROJECTS[name])
    # Build output, dependencies and environments are ignored, as in a real repository
    with open(os.path.join(root, ".gitignore"), "w") as f:
        f.write("node_modules/\nbuild/\nPods/\nvenv/\nwandb/\n")
    git(root, "init", "-q")
    git(root, "add", "-A")
    git(root, "commit", "-q", "-m", "Initial commit")
    setup = setup or {}
    if "commit" in setup:
        _apply(root, setup["commit"])
        git(root, "add", "-A")
        git(root, "commit", "-q", "-m", setup.get("message", "Update"))
    if "edit" in setup:
        _apply(root, setup["edit"])


def _apply(root, changes):
    for rel, content in changes.items():
        path = os.path.join(root, rel)
        if content is None:
            os.remove(path)
        else:
            write_files(root, {rel: content})


def snapshot(root):
    """{relative path: bytes} for every file outside .git, to check that a run changed nothing."""
    files = {}
    for folder, dirs, names in os.walk(root):
        dirs[:] = [d for d in dirs if d != ".git"]
        for name in names:
            path = os.path.join(folder, name)
            with open(path, "rb") as f:
                files[os.path.relpath(path, root)] = f.read()
    return files
